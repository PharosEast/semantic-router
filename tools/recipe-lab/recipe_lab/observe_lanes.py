"""Cold-start C2 (lane mode): observe which template lane each case hits.

The template path (sub-issue-8 §2.2 step 3) replaces the legacy 14-domain
seed config: an observation config is generated by the upstream entrypoint
``vllm-sr recipe builtin init`` - the template recipe is bound, lane by lane,
to placeholder models served by the mock backend (answers are irrelevant;
only the lane decision matters). The template pins its own decision model
(``_bundle_decision_model`` copies the bundle's deployment when the provider
config declares none), so lane assignment depends only on the decision
model's answers and the rules - never on the bound placeholder. Y2's
label-agreement check is therefore unnecessary on this path.

Facts this module encodes (verified against upstream main ``718845ddc``):

- ``recipe builtin list`` (src/vllm-sr/cli/commands/recipe_builtin.py)
  reports, per bundle and recipe, every decision's ``minimum_candidates``
  and algorithm; a decision with a ``fast_response`` plugin responds
  immediately (``_requires_backend``) and needs no binding.
- ``initialize_builtin_recipe`` refuses an existing output, requires the
  bindings to cover exactly the backend decisions, requires every ref's
  model to exist in the provider config, and enforces each lane's
  ``minimum_candidates`` (distinct ``lora_name or model`` refs).
- The mom-v1 bundle enables ``global.services.router_replay`` (store_backend
  postgres, async off), so the observation config captures one replay record
  per request; the record's ``decision`` field IS the lane name.
- The recipe's ``candidate_requirements`` demand declared capabilities and
  known context limits, so every placeholder model gets an explicit
  modelCard (the final bindings generation repeats this for real models).

Lane capability requirements are read from the template's lane descriptions
(mom-v1 recipe.dsl): vision needs an image-capable model, agentic needs tool
calling, long_context needs a 200K+ context window. Other lanes carry no
capability requirement. The table is data, validated against the template's
lane names, and shared with bindings.py.
"""

from __future__ import annotations

import json
import subprocess
from collections import Counter
from pathlib import Path
from typing import Any

import yaml

from .contract import LONG_CONTEXT_MIN_TOKENS, ContractError, dataset_content_hash
from .observe_labels import labels_from_records
from .runner import RunnerEnv, probe_records

OBSERVE_SCHEMA = "recipe-lab-observe-lanes-v1"
# Entrypoint model name of the observation config (``recipe builtin init
# --model-name``); the CLI exposes it, this is the default.
OBSERVE_MODEL_NAME = "vllm-sr/auto"
# x-request-id tag for the lane-observe probe (distinct from the legacy
# observe-labels prefix so a shared replay store cannot cross-join).
REQUEST_ID_PREFIX = "rl-observe-lanes-"
PLACEHOLDER_PREFIX = "rl-observe-placeholder"

# Lane -> capability requirement, encoded from the template lane
# descriptions (mom-v1 recipe.dsl L127/L138/L160: "a model with a long
# context window" / "a model that reads images" / "a strong agent"). Lanes
# not listed have no capability requirement; requirements for lanes the
# template does not declare are ignored (validated in bindings planning).
LANE_CAPABILITY_REQUIREMENTS: dict[str, dict[str, Any]] = {
    "vision": {"capabilities": ("vision",), "min_context_window": None},
    "agentic": {"capabilities": ("tools",), "min_context_window": None},
    "long_context": {
        "capabilities": (),
        "min_context_window": LONG_CONTEXT_MIN_TOKENS,
    },
}

_HTTP_OK = 200


def _run_json(argv: list[str], *, timeout_s: float, what: str) -> dict[str, Any]:
    """Run a vllm-sr command that prints one JSON document to stdout."""
    try:
        proc = subprocess.run(
            argv,
            check=False,
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            timeout=timeout_s,
        )
    except OSError as exc:
        raise ContractError(f"{what} could not start: {exc}") from exc
    except subprocess.TimeoutExpired as exc:
        raise ContractError(f"{what} exceeded the trial budget: {exc}") from exc
    if proc.returncode != 0:
        tail = (proc.stdout or "")[-4000:]
        raise ContractError(f"{what} failed (exit {proc.returncode}):\n{tail}")
    try:
        return json.loads(proc.stdout)
    except json.JSONDecodeError as exc:
        raise ContractError(f"{what} did not print valid JSON: {exc}") from exc


def template_info(
    *,
    bundle: str,
    recipe: str,
    vllm_sr_bin: str = "vllm-sr",
    catalog_version: str = "latest",
    timeout_s: float = 120.0,
    run_json: Any = _run_json,
) -> dict[str, Any]:
    """Read the template's lanes from ``vllm-sr recipe builtin list``.

    Returns ``{"bundle", "sha256", "recipe", "lanes": {name:
    {"algorithm", "minimum_candidates", "immediate"}}}``. ``immediate``
    lanes respond without a backend (fast_response) and bind to ``[]``.
    """
    document = run_json(
        [
            str(vllm_sr_bin),
            "recipe",
            "builtin",
            "list",
            "--catalog-version",
            catalog_version,
        ],
        timeout_s=timeout_s,
        what="recipe builtin list",
    )
    bundles = {entry["name"]: entry for entry in document.get("bundles") or []}
    if bundle not in bundles:
        known = ", ".join(sorted(bundles)) or "none"
        raise ContractError(
            f"template bundle {bundle!r} is not installed (catalog "
            f"{catalog_version!r}); installed: {known}"
        )
    entry = bundles[bundle]
    recipes = {item["name"]: item for item in entry.get("recipes") or []}
    if recipe not in recipes:
        known = ", ".join(sorted(recipes)) or "none"
        raise ContractError(
            f"bundle {bundle!r} has no recipe {recipe!r}; recipes: {known}"
        )
    lanes: dict[str, dict[str, Any]] = {}
    for decision in recipes[recipe].get("decisions") or []:
        minimum = decision.get("minimum_candidates")
        if not isinstance(minimum, int) or minimum < 0:
            raise ContractError(
                f"template lane {decision.get('name')!r} has no usable "
                "minimum_candidates"
            )
        lanes[decision["name"]] = {
            "algorithm": decision.get("algorithm"),
            "minimum_candidates": minimum,
            "immediate": decision.get("algorithm") is None,
        }
    if not lanes:
        raise ContractError(
            f"template {bundle}/{recipe} declares no decisions: nothing to bind"
        )
    return {
        "bundle": bundle,
        "recipe": recipe,
        "sha256": entry.get("sha256"),
        "catalog_version": catalog_version,
        "lanes": lanes,
    }


def lane_requirements(lane: str) -> dict[str, Any]:
    """The capability requirement of one lane (empty for unlisted lanes)."""
    return LANE_CAPABILITY_REQUIREMENTS.get(
        lane, {"capabilities": (), "min_context_window": None}
    )


def capability_satisfied(requirement: dict[str, Any], capabilities: Any) -> bool:
    """True when one model's declared ModelCapabilities meet a requirement."""
    for name in requirement.get("capabilities") or ():
        if not getattr(capabilities, name, False):
            return False
    window = requirement.get("min_context_window")
    return not (
        window is not None
        and (
            capabilities.context_window is None
            or capabilities.context_window < window
        )
    )


def placeholder_models(count: int, backend_endpoint: str) -> list[dict[str, Any]]:
    """``count`` placeholder provider models on the observation backend.

    The placeholders exist only to satisfy ``minimum_candidates`` while the
    router observes lanes; their answers are irrelevant.
    """
    return [
        {
            "name": f"{PLACEHOLDER_PREFIX}-{index}",
            "provider_model_id": f"{PLACEHOLDER_PREFIX}-{index}",
            "api_format": "openai",
            "backend_refs": [
                {
                    "name": f"{PLACEHOLDER_PREFIX}-{index}-backend",
                    "endpoint": backend_endpoint,
                    "protocol": "http",
                    "provider": "vllm",
                    "weight": 1,
                }
            ],
        }
        for index in range(1, count + 1)
    ]


def observation_providers_config(
    *,
    placeholder_count: int,
    backend_endpoint: str,
    listener_port: int = 8899,
) -> dict[str, Any]:
    """The synthetic provider config ``recipe builtin init --config`` consumes.

    Canonical v0.3 shape (mirrors the proven seed config): one listener,
    the placeholder models, explicit modelCards (the recipe's
    ``candidate_requirements`` demand declared capabilities), and the
    response cache disabled - a warm cache would swallow repeated cases
    before any decision fires and lose their lane observation. The decision
    model is deliberately NOT declared: init copies the bundle's pinned
    deployment, which is the point of the template path (sub-issue-8 §2.2
    step 3).
    """
    models = placeholder_models(placeholder_count, backend_endpoint)
    return {
        "version": "v0.3",
        "listeners": [
            {
                "name": "http-observe",
                "address": "0.0.0.0",
                "port": listener_port,
                "timeout": "300s",
            }
        ],
        "providers": {"defaults": {"model": models[0]["name"]}, "models": models},
        "routing": {
            "modelCards": [
                {
                    "name": model["name"],
                    "context_window_size": 32768,
                    "description": (
                        "Lane observation placeholder; answers are irrelevant."
                    ),
                    "capabilities": ["chat", "text"],
                    "modality": "text",
                }
                for model in models
            ]
        },
        "global": {
            "stores": {"response_cache": {"enabled": False, "backend_type": "memory"}},
        },
    }


def observation_bindings(template: dict[str, Any]) -> dict[str, list[dict[str, Any]]]:
    """Placeholder bindings covering every backend lane of the template.

    Lanes are processed in sorted order and each takes its
    ``minimum_candidates`` distinct placeholder refs (frontier's two come
    from two distinct placeholder model names). Immediate lanes bind to
    ``[]``. Returns ``(bindings, placeholder_count)`` so the provider config
    declares exactly the models the bindings reference.
    """
    bindings: dict[str, list[dict[str, Any]]] = {}
    placeholders: list[str] = []

    def take(count: int) -> list[dict[str, Any]]:
        refs = []
        while len(placeholders) < count:
            placeholders.append(f"{PLACEHOLDER_PREFIX}-{len(placeholders) + 1}")
        for name in placeholders[:count]:
            refs.append({"model": name})
        return refs

    for lane in sorted(template["lanes"]):
        info = template["lanes"][lane]
        if info["immediate"]:
            bindings[lane] = []
        else:
            bindings[lane] = take(info["minimum_candidates"])
    return bindings, len(placeholders)


def _yaml_text(document: dict[str, Any]) -> str:
    return yaml.safe_dump(document, sort_keys=False, allow_unicode=True)


def build_observation_config(
    *,
    template: dict[str, Any],
    out_dir: str | Path,
    backend_endpoint: str,
    vllm_sr_bin: str = "vllm-sr",
    model_name: str = OBSERVE_MODEL_NAME,
    listener_port: int = 8899,
    timeout_s: float = 300.0,
    run_json: Any = _run_json,
) -> dict[str, Any]:
    """Generate the observation config via ``recipe builtin init``.

    Writes ``providers-observe.yaml`` and ``bindings-observe.yaml``, runs
    init to produce ``observe-config.yaml``, then disables the response
    cache in the generated config (the bundle may enable it; a warm cache
    would swallow repeated cases before any decision fires). Returns the
    paths and provenance (bundle sha, lanes, init command, placeholder
    bindings).
    """
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    bindings, placeholder_count = observation_bindings(template)
    providers = observation_providers_config(
        placeholder_count=placeholder_count,
        backend_endpoint=backend_endpoint,
        listener_port=listener_port,
    )
    providers_path = out / "providers-observe.yaml"
    providers_path.write_text(_yaml_text(providers), encoding="utf-8")
    bindings_path = out / "bindings-observe.yaml"
    # init passes the YAML document straight to compose_builtin_recipe: the
    # file's top level IS the {lane: [modelRef, ...]} mapping.
    bindings_path.write_text(_yaml_text(bindings), encoding="utf-8")

    config_path = out / "observe-config.yaml"
    argv = [
        str(vllm_sr_bin),
        "recipe",
        "builtin",
        "init",
        str(template["recipe"]),
        "--bundle",
        str(template["bundle"]),
        "--config",
        str(providers_path),
        "--bindings",
        str(bindings_path),
        "--model-name",
        model_name,
        "--output",
        str(config_path),
    ]
    run_json(argv, timeout_s=timeout_s, what="recipe builtin init")
    if not config_path.is_file():
        raise ContractError(
            f"recipe builtin init reported success but wrote no config: {config_path}"
        )

    # Evaluation guard: force the response cache off in the generated config.
    config = yaml.safe_load(config_path.read_text(encoding="utf-8"))
    if not isinstance(config, dict):
        raise ContractError(f"{config_path} is not a YAML mapping")
    stores = (config.get("global") or {}).get("stores") or {}
    cache = stores.get("response_cache")
    cache_disabled = False
    if isinstance(cache, dict) and cache.get("enabled"):
        cache["enabled"] = False
        config_path.write_text(_yaml_text(config), encoding="utf-8")
        cache_disabled = True

    return {
        "config": str(config_path),
        "providers": str(providers_path),
        "bindings": str(bindings_path),
        "init_command": argv,
        "bundle_sha256": template["sha256"],
        "lanes": template["lanes"],
        "placeholder_bindings": bindings,
        "cache_disabled": cache_disabled,
    }


def lane_for_decision(decision: str) -> str:
    """In a template config every matched decision IS the lane name."""
    return (decision or "").strip()


def lane_rows_from_records(
    records: list[dict[str, Any]], cases: list[dict[str, Any]]
) -> tuple[list[dict[str, Any]], dict[str, int]]:
    """Join replay records to cases by request id; the lane is the record's
    matched decision name (identity mapping, see observe_labels)."""

    rows, stats = labels_from_records(
        records, cases, label_of=lane_for_decision, request_id_prefix=REQUEST_ID_PREFIX
    )
    lanes = [
        {
            "case_id": row["case_id"],
            "lane": row["router_label"],
            "confidence": row["confidence"],
        }
        for row in rows
    ]
    return lanes, stats


def observe_lanes_split(
    *,
    env: RunnerEnv,
    config: str | Path,
    cases: list[dict[str, Any]],
    router_model: str = OBSERVE_MODEL_NAME,
    request_timeout: float = 180.0,
    trial_timeout_s: float | None = None,
) -> dict[str, Any]:
    """Observe one case split through the observation config (C2 lane mode).

    Boots the stack once via probe_records with tagged request ids, joins
    the records to cases by request id, and summarizes the lane
    distribution. Lane coverage is computed against the FULL case count (a
    lost record is never covered).
    """
    records, statuses, timings = probe_records(
        env,
        config,
        cases,
        router_model=router_model,
        request_timeout=request_timeout,
        trial_timeout_s=trial_timeout_s,
        request_id_prefix=REQUEST_ID_PREFIX,
    )
    rows, stats = lane_rows_from_records(records, cases)
    lane_counts = dict(sorted(Counter(row["lane"] for row in rows).items()))
    summary = {
        "cases": len(cases),
        "observed": len(rows),
        "missing": stats["missing"],
        "lane_coverage": round(len(rows) / len(cases), 6) if cases else 0.0,
        "lane_counts": lane_counts,
        "non_200_requests": sum(
            1 for status in statuses.values() if status != _HTTP_OK
        ),
    }
    return {
        "rows": rows,
        "stats": stats,
        "statuses": statuses,
        "timings": timings,
        "summary": summary,
    }


def write_lanes(rows: list[dict[str, Any]], path: str | Path) -> Path:
    """Byte-stable lanes JSONL (sorted rows, sorted keys)."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    ordered = sorted(rows, key=lambda row: row["case_id"])
    with path.open("w", encoding="utf-8") as fh:
        for row in ordered:
            fh.write(json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n")
    return path


def write_lanes_summary(summary: dict[str, Any], path: str | Path) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(summary, ensure_ascii=False, sort_keys=True, indent=2) + "\n",
        encoding="utf-8",
    )
    return path


def observation_config_fingerprint(path: str | Path) -> str:
    """The observation config identity for provenance (sha256 of bytes)."""
    return dataset_content_hash(path)
